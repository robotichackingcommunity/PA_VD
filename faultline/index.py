"""Build index.json, stats.json and the README coverage block from CVE-json/."""
from __future__ import annotations

import collections
import json
import logging
import os
import re
from pathlib import Path
from typing import Any

from .records import iter_record_files, load_json, repo_root
from .taxonomy import DOMAINS, LAYERS

log = logging.getLogger("faultline.index")
STATS_START, STATS_END = "<!-- stats:start -->", "<!-- stats:end -->"


def _names(items: list) -> list[str]:
    out = []
    for x in items or []:
        name = x.get("name") if isinstance(x, dict) else x
        if isinstance(name, str) and name:
            out.append(name)
    return out


def index_entry(rec: dict, file_name: str) -> dict[str, Any]:
    tax = rec.get("taxonomy", {})
    cvss = rec.get("cvss", {}) if isinstance(rec.get("cvss"), dict) else {}
    cwe = rec.get("cwe", {}) if isinstance(rec.get("cwe"), dict) else {}
    entry = {
        "cve_id": rec.get("cve_id"),
        "title": rec.get("title"),
        "published": rec.get("published"),
        "last_modified": rec.get("last_modified"),
        "vuln_status": rec.get("vuln_status"),
        "score": cvss.get("score"),
        "severity": cvss.get("severity"),
        "cvss_version": cvss.get("version"),
        "cwe": cwe.get("id"),
        "domains": [d["domain"] for d in tax.get("physical_ai_domain", []) if isinstance(d, dict)],
        "primary_domain": next((d["domain"] for d in tax.get("physical_ai_domain", []) if isinstance(d, dict)), None),
        "layers": [l["layer"] for l in tax.get("technical_layer", []) if isinstance(l, dict)],
        "vendors": _names(tax.get("vendor", [])),
        "products": _names(tax.get("product", [])),
        "tags": rec.get("cross_domain_tags", []),
        "robot_safety_impact": (rec.get("impact") or {}).get("robot_safety_impact") if isinstance(rec.get("impact"), dict) else None,
        "enrichment": (rec.get("enrichment") or {}).get("method", "curated") if isinstance(rec.get("enrichment"), dict) else "curated",
        "reviewed": (rec.get("enrichment") or {}).get("reviewed", True) if isinstance(rec.get("enrichment"), dict) else True,
        "file_name": file_name,
    }
    return {k: v for k, v in entry.items() if v is not None}


def build_stats(entries: list[dict]) -> dict[str, Any]:
    c = collections.Counter
    sev = c(e.get("severity") or "UNKNOWN" for e in entries)
    dom = c(d for e in entries for d in e.get("domains", []))
    prim = c(e.get("primary_domain") for e in entries if e.get("primary_domain"))
    lay = c(l for e in entries for l in e.get("layers", []))
    ven = c(v for e in entries for v in e.get("vendors", []))
    tags = c(t for e in entries for t in e.get("tags", []))
    year = c((e.get("published") or "unknown")[:4] for e in entries)
    status = c(e.get("vuln_status") or "unknown" for e in entries)
    enrich = c(e.get("enrichment", "curated") for e in entries)
    return {
        "generated_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "total": len(entries),
        "severity": {k: sev.get(k, 0) for k in ("CRITICAL", "HIGH", "MEDIUM", "LOW", "NONE", "UNKNOWN") if sev.get(k)},
        "domains": {d: dom.get(d, 0) for d in DOMAINS},
        "primary_domains": {d: prim.get(d, 0) for d in DOMAINS},
        "layers": {l: lay.get(l, 0) for l in LAYERS},
        "vendors": dict(ven.most_common()),
        "top_tags": dict(tags.most_common(25)),
        "published_year": dict(sorted(year.items())),
        "vuln_status": dict(status.most_common()),
        "enrichment": dict(enrich.most_common()),
        "unreviewed_auto_records": sum(1 for e in entries if not e.get("reviewed", True)),
    }


def readme_block(stats: dict[str, Any]) -> str:
    sev = stats["severity"]
    dom = " · ".join(f"{k} ({v})" for k, v in sorted(stats["domains"].items(), key=lambda kv: -kv[1]) if v)
    lay = " · ".join(f"{k} ({v})" for k, v in sorted(stats["layers"].items(), key=lambda kv: -kv[1]) if v)
    vendors = ", ".join(k for k, _ in list(stats["vendors"].items())[:14])
    tags = ", ".join(f"`{t}`" for t in list(stats["top_tags"])[:10])
    lines = [
        STATS_START,
        f"_Auto-generated by `python3 -m faultline index` on {stats['generated_at'][:10]} — do not edit by hand._",
        "",
        f"- **{stats['total']}** enriched vulnerability records (see [`index.json`](./index.json) for the lightweight index, [`stats.json`](./stats.json) for all counts)",
        f"- **Severity:** {sev.get('CRITICAL', 0)} Critical · {sev.get('HIGH', 0)} High · {sev.get('MEDIUM', 0)} Medium · {sev.get('LOW', 0)} Low (CVSS-based)",
        f"- **Physical AI domains** (a record may belong to several): {dom}",
        f"- **Technical layers** (where in the stack the flaw lives): {lay}",
        f"- **Notable vendors/projects tracked:** {vendors}, and more",
        f"- **Frequent `cross_domain_tags`:** {tags}",
    ]
    if stats.get("unreviewed_auto_records"):
        lines.append(f"- **Pending human review:** {stats['unreviewed_auto_records']} auto-enriched record(s) (`enrichment.reviewed = false`)")
    lines.append(STATS_END)
    return "\n".join(lines)


def update_readme(stats: dict[str, Any], path: Path | None = None) -> bool:
    path = path or repo_root() / "README.md"
    if not path.exists():
        return False
    text = path.read_text(encoding="utf-8")
    block = readme_block(stats)
    if STATS_START in text and STATS_END in text:
        new = re.sub(re.escape(STATS_START) + r".*?" + re.escape(STATS_END), lambda _: block, text, flags=re.S)
    else:
        # First run: replace the hand-written "Current Coverage" + "Attack Surface" sections.
        pattern = r"### Current Coverage \(snapshot\)\n.*?(?=\n### Case Studies)"
        if re.search(pattern, text, flags=re.S):
            new = re.sub(pattern, lambda _: "### Current Coverage\n\n" + block + "\n", text, flags=re.S)
        else:
            new = text.rstrip() + "\n\n## Current Coverage\n\n" + block + "\n"
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def build_all() -> dict[str, Any]:
    root = repo_root()
    entries = []
    for p in iter_record_files(root):
        try:
            rec = load_json(p)
        except ValueError as exc:
            log.error("%s: invalid JSON, skipped from index (%s)", p.name, exc)
            continue
        entries.append(index_entry(rec, p.name))
    entries.sort(key=lambda e: (e.get("published") or "", e.get("cve_id") or ""), reverse=True)
    stats = build_stats(entries)
    for name, payload in (("index.json", entries), ("stats.json", stats)):
        target = root / name
        tmp = target.with_suffix(".tmp")
        tmp.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        os.replace(tmp, target)
    readme_changed = update_readme(stats)
    log.info("index: %d records, readme %s", len(entries), "updated" if readme_changed else "unchanged")
    return {"records": len(entries), "severity": stats["severity"], "layers": stats["layers"], "readme_updated": readme_changed}
